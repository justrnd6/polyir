#!/usr/bin/env python3
"""Copies stdlib/Math.poly, Gpu.poly, Text.poly and Lists.poly into the compiler: core/src/front/PreludeText.cpp.

Four small libraries are available to every program WITHOUT an import: the Math functions (`sign`, `fract`, `clamp`,
`mix`), the CPU side of the GPU functions (`atomicAdd`, `barrier`, `groupSize`, ...), the Text functions (`split`,
`trim`, `join`, ...) and the Lists functions (`first`, `last`, `drop`). When a program calls one and defines none of them, the compiler adds the library on its own
(core/src/front/Prelude.cpp). A compiler is a program of its own and cannot read stdlib/ when it runs, so the libraries'
text is embedded in it, in PreludeText.cpp as raw string literals. Run this after editing any of the four files.

  python3 core/stdlib/sync-prelude.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
CPP_TARGET = os.path.join(HERE, "..", "src", "front", "PreludeText.cpp")           # core/stdlib -> core/src/front

# (C++ function, file)
LIBRARIES = [("MathPreludeText", "Math.poly"), ("GpuPreludeText", "Gpu.poly"), ("TextPreludeText", "Text.poly"),
             ("ListsPreludeText", "Lists.poly")]

CPP_HEADER = """// The text of the four libraries built into the language (the Math functions, the CPU side of the GPU functions, the Text
// functions and the Lists functions): core/stdlib/Math.poly, Gpu.poly, Text.poly and Lists.poly. GENERATED by core/stdlib/sync-prelude.py: edit the .poly file, then run it.
// Prelude.cpp parses each once per process.
#include "front/PreludeText.hpp"

namespace polyir::front {
"""

# The end of a C++ raw string literal.
CPP_END = ")prelude\""


def source(filename):
    return open(os.path.join(HERE, filename), encoding="utf-8").read()


def cpp_function(function, filename):
    text = source(filename)
    if CPP_END in text:
        raise SystemExit(filename + " contains " + CPP_END + ", which the copy cannot hold")
    return "\n  StringView " + function + "() {\n    return R\"prelude(" + text + CPP_END + ";\n  }\n"


def main():
    with open(CPP_TARGET, "w", encoding="utf-8") as out:
        out.write(CPP_HEADER + "".join(cpp_function(c, f) for c, f in LIBRARIES) + "\n}  // namespace polyir::front\n")
    print("wrote", os.path.normpath(CPP_TARGET))


main()
