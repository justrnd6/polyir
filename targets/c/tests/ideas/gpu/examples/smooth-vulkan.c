static float smooth(int32_t i, float* src, int32_t n);
static int64_t main_(void);
static int64_t compareWithCpu(int64_t gpu, int64_t pipeline);

static float smooth(int32_t i, float* src, int32_t n) {
  if (i == 0) {
    return src[i];
  }
  if (i == n - 1) {
    return src[i];
  }
  return (src[i - 1] + src[i] + src[i + 1]) / 3.0f;
}

static int64_t main_(void) {
  int64_t gpu = vulkanStart();
  if (gpu == 0) {
    return 10;
  }
  int64_t pipeline = vulkanPipeline(gpu, "smooth.spv", 2, 8);
  if (pipeline == 0) {
    return 11;
  }
  return compareWithCpu(gpu, pipeline);
}

static int64_t compareWithCpu(int64_t gpu, int64_t pipeline) {
  List* xs = listFilled(sizeof(float), 6, (float[]){0.0f});
  LIST_AT(xs, 0, float) = 3.0f;
  LIST_AT(xs, 1, float) = 9.0f;
  LIST_AT(xs, 2, float) = 0.0f;
  LIST_AT(xs, 3, float) = 6.0f;
  LIST_AT(xs, 4, float) = 12.0f;
  LIST_AT(xs, 5, float) = 3.0f;
  int64_t input = vulkanBuffer(gpu, (int64_t) xs, 24);
  int64_t output = vulkanEmptyBuffer(gpu, 24);
  if (input == 0 || output == 0) {
    return 12;
  }
  List* push = listFilled(sizeof(int32_t), 2, (int32_t[]){0});
  LIST_AT(push, 0, int32_t) = 6;
  LIST_AT(push, 1, int32_t) = 6;
  if (vulkanDispatch(gpu, pipeline, 6, (int64_t) push, input, output, 0, 0) == 0) {
    return 12;
  }
  float* results = (int8_t*) (intptr_t) vulkanContents(output);
  float* cpuInput = (int8_t*) (intptr_t) (int64_t) xs;
  for (int64_t i = 0; i < 6; i = i + 1) {
    if (results[i] != smooth((int32_t) i, cpuInput, 6)) {
      return 13;
    }
  }
  return 0;
}

int main(void) {
  return (int) main_();
}
