struct Pt;
struct Contact;

struct Pt {
  int64_t x;
  int64_t y;

  Pt(int64_t x, int64_t y) : x(x), y(y) {}

  bool operator==(const Pt& other) const {
    return allSame(x, other.x, y, other.y);
  }

  std::size_t hash() const {
    return hashAll(x, y);
  }
};

struct Contact {
  std::string name;
  std::optional<std::string> nickname;

  Contact(std::string name, std::optional<std::string> nickname) : name(name), nickname(nickname) {}

  bool operator==(const Contact& other) const {
    return allSame(name, other.name, nickname, other.nickname);
  }

  std::size_t hash() const {
    return hashAll(name, nickname);
  }
};

std::optional<int64_t> find(List<int64_t> xs, int64_t want);
std::optional<Ref<Pt>> firstPoint(int64_t ok);
std::string shown(Ref<Contact> c);

inline std::optional<int64_t> find(List<int64_t> xs, int64_t want) {
  for (int64_t i = 0; i < (int64_t) xs->size(); i = i + 1) {
    if (xs->at(i) == want) {
      return std::optional<int64_t>(i);
    }
  }
  return std::optional<int64_t>();
}

inline std::optional<Ref<Pt>> firstPoint(int64_t ok) {
  if (ok == 1) {
    return std::optional<Ref<Pt>>(std::make_shared<Pt>(7, 8));
  }
  return std::optional<Ref<Pt>>();
}

inline std::string shown(Ref<Contact> c) {
  if ((c->nickname).has_value()) {
    return present(c->nickname);
  }
  return c->name;
}

int main() {
  const List<int64_t> xs = newList<int64_t>();
  xs->push_back(10);
  xs->push_back(20);
  int64_t score = 0;
  const std::optional<int64_t> hit = find(xs, 20);
  if (hit.has_value()) {
    score = score + present(hit);
  }
  if (!find(xs, 99).has_value()) {
    score = score + 10;
  }
  const std::optional<Ref<Pt>> p = firstPoint(1);
  if (p.has_value()) {
    score = score + present(p)->x;
  }
  if (!firstPoint(0).has_value()) {
    score = score + 100;
  }
  const Ref<Contact> named = std::make_shared<Contact>("ann"s, std::optional<std::string>("annie"s));
  const Ref<Contact> plain = std::make_shared<Contact>("bo"s, std::optional<std::string>());
  if (shown(named) == "annie"s) {
    score = score + 1000;
  }
  if (shown(plain) == "bo"s) {
    score = score + 2000;
  }
  return score;
}
