#!/usr/bin/env python3
"""Embeds meta-build in the `poly` command: writes runtime/tools/MetaBuildText.cpp, the runner (src/Up.poly) and
everything it imports joined into one program with the imports taken out, one C++ raw string per file. `poly up` checks
that program and runs it on the VM, so `poly` needs nothing beside it. Run this after editing any file under
tools/metabuild/src (Host.poly among them):

  python3 tools/metabuild/sync-embed.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
TARGET = os.path.join(HERE, "..", "..", "runtime", "tools", "MetaBuildText.cpp")   # tools/metabuild -> runtime/tools
ENTRY = os.path.join(HERE, "src", "Up.poly")
# build.poly's hook: kept apart, since `poly` checks a project's build.poly in its place.
EXTEND = os.path.normpath(os.path.join(HERE, "src", "Extend.poly"))
# Each file is one raw string, which ends at this mark: no file may hold it.
END = ")polyir\""
IMPORT = re.compile(r'^import "([^"]+)"\s*$', re.M)


def gather(path, seen, order):
    path = os.path.normpath(path)
    if path in seen:
        return
    seen.add(path)
    text = open(path, encoding="utf-8").read()
    for rel in IMPORT.findall(text):
        gather(os.path.join(os.path.dirname(path), rel), seen, order)
    order.append((path, IMPORT.sub("", text)))


def copied(files):
    parts = []
    for path, text in files:
        if END in text:
            raise SystemExit(path + " contains " + END + ", which ends the raw string that holds it")
        named = "// ── " + os.path.relpath(path, os.path.join(HERE, "..", "..")) + "\n" + text.strip() + "\n\n"
        parts.append('    R"polyir(' + named + END)
    return "\n".join(parts)


def main():
    order = []
    gather(ENTRY, set(), order)
    program = copied([f for f in order if f[0] != EXTEND])
    extension = copied([f for f in order if f[0] == EXTEND])
    with open(TARGET, "w", encoding="utf-8") as out:
        out.write("// GENERATED by tools/metabuild/sync-embed.py from tools/metabuild/src: do not edit.\n")
        out.write("// meta-build as one polyir program (the runner and all it imports), for `poly up`.\n")
        out.write('#include "MetaBuildText.hpp"\n\nnamespace polyir::poly {\n\n')
        out.write("  const char* MetaBuildProgram() {\n    return\n" + program + ";\n  }\n\n")
        out.write("  // What stands in for a project's build.poly when it has none (src/Extend.poly).\n")
        out.write("  const char* MetaBuildNoExtension() {\n    return\n" + extension + ";\n  }\n\n}  // namespace polyir::poly\n")
    print("wrote", os.path.normpath(TARGET), "(" + str(len(order)) + " files)")


main()
